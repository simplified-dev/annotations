package dev.simplified.classbuilder.apt;

import dev.simplified.shared.apt.MemberShape;

import javax.lang.model.element.AnnotationMirror;
import javax.lang.model.element.AnnotationValue;
import javax.lang.model.element.ExecutableElement;
import javax.lang.model.element.TypeElement;
import javax.lang.model.element.TypeParameterElement;
import javax.lang.model.type.TypeMirror;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.TreeSet;

/**
 * Emits a concrete {@code <InterfaceName>Impl} class that implements an
 * interface annotated with {@code @ClassBuilder(generateImpl = true)} (the
 * default). Fields are derived from the interface's abstract zero-arg
 * accessors; the class is package-private, final, and provides an all-args
 * constructor, accessor methods that satisfy the interface contract, and
 * {@code equals}/{@code hashCode}/{@code toString} based on the fields.
 *
 * <p>An accessor's {@code @BuildFlag} is copied onto the field it produces.
 * That copy is what makes constraints work on an interface target at all: the
 * validator reads the declared fields of the instance {@code build()}
 * constructs, and this class is that instance.
 *
 * <p>The three whole-object members are written from an {@link ImplPlan} for
 * the same reason, one step further on: this class is the only one a caller
 * ever holds, so an {@code @EqualsAndHashCode} or {@code @ToString} on the
 * interface has to be honoured here or it does nothing whatsoever. Each member
 * is spelled through {@link MemberShape}, the table the mutation path reads,
 * so one library does not ship two answers for what an array is worth.
 *
 * <p>Every helper those members call is written fully qualified rather than
 * imported. A field name obscures a type of the same simple name, and the field
 * names here are the interface's accessor names verbatim - so an accessor
 * called {@code Arrays} or {@code Objects}, or an inherited constant of that
 * name, turns {@code Arrays.equals(...)} into a call on the field. The mutation
 * path is immune because it builds every such reference through
 * {@code JavacTypeFactory.qualIdent}, and this is the source-level spelling of
 * the same decision.
 */
final class InterfaceImplEmitter {

    private static final String BUILD_FLAG_FQN = "dev.simplified.annotations.BuildFlag";
    private static final String ARRAYS_FQN = "java.util.Arrays";
    private static final String OBJECTS_FQN = "java.util.Objects";
    private static final String FLOAT_FQN = "java.lang.Float";
    private static final String DOUBLE_FQN = "java.lang.Double";

    /** The odd prime the hash accumulator scales by, matching the mutation path. */
    private static final int PRIME = 59;

    private InterfaceImplEmitter() {}

    static String emit(TypeElement target, String packageName, String implName, List<FieldSpec> fields,
                       boolean emitGenerated, ImplPlan plan) {
        StringBuilder sb = new StringBuilder(2048);
        sb.append("// Generated by @ClassBuilder - do not edit\n");
        if (!packageName.isEmpty()) sb.append("package ").append(packageName).append(";\n\n");

        TreeSet<String> imports = new TreeSet<>();
        List<String> fieldTypes = new ArrayList<>(fields.size());
        for (FieldSpec f : fields) fieldTypes.add(simplifyType(f.typeDisplay, packageName, imports));
        // Copied off the accessor, because the validator reads the constructed
        // instance's declared fields and this class holds them. Rendered here
        // rather than at the field loop below for the same reason the type
        // parameters are - emitting one adds its own import.
        List<String> fieldFlags = new ArrayList<>(fields.size());
        for (FieldSpec f : fields) fieldFlags.add(renderBuildFlag(f.buildFlag, packageName, imports));
        // A generic interface propagates its parameters onto the impl, which is
        // a separate top-level class and so cannot see the interface's. Resolved
        // before the import block is written, since a bound can import types.
        String typeParamDecl = typeParamDecl(target, packageName, imports);
        String typeArgs = typeArgs(target);
        for (String imp : imports) sb.append("import ").append(imp).append(";\n");
        if (!imports.isEmpty()) sb.append('\n');

        String interfaceName = target.getSimpleName().toString();
        // Type-level, for the reason given on BuilderEmitter.emitClassHeader:
        // every member here is generated. Fully qualified so it needs no
        // import and cannot collide with javax/jakarta @Generated.
        if (emitGenerated) sb.append("@dev.simplified.annotations.Generated\n");
        sb.append("final class ").append(implName).append(typeParamDecl)
            .append(" implements ").append(interfaceName).append(typeArgs).append(" {\n\n");

        // Fields
        for (int i = 0; i < fields.size(); i++) {
            sb.append("    ").append(fieldFlags.get(i)).append("private final ")
                .append(fieldTypes.get(i)).append(' ').append(fields.get(i).name).append(";\n");
        }
        sb.append('\n');

        // All-args constructor (package-private)
        sb.append("    ").append(implName).append('(');
        for (int i = 0; i < fields.size(); i++) {
            if (i > 0) sb.append(", ");
            sb.append(fieldTypes.get(i)).append(' ').append(fields.get(i).name);
        }
        sb.append(") {\n");
        for (FieldSpec f : fields) sb.append("        this.").append(f.name).append(" = ").append(f.name).append(";\n");
        sb.append("    }\n\n");

        // Accessor implementations
        for (int i = 0; i < fields.size(); i++) {
            FieldSpec f = fields.get(i);
            sb.append("    @Override public ").append(fieldTypes.get(i)).append(' ').append(f.name).append("() { return this.").append(f.name).append("; }\n");
        }
        sb.append('\n');

        sb.append(renderWholeObject(implName, wildcardArgs(target), plan));

        sb.append("}\n");
        return sb.toString();
    }

    /**
     * Renders {@code equals}, {@code hashCode} and {@code toString} as the plan
     * configures them.
     *
     * @param implName the class being emitted, used as its own {@code instanceof}
     *        operand and as the {@code toString} prefix
     * @param wildcardArgs one wildcard per type parameter in reference form,
     *        empty when the impl is not generic
     * @param plan the members and formatting resolved off the interface
     * @return the three members, indented and separated as the body wants them
     */
    private static String renderWholeObject(String implName, String wildcardArgs, ImplPlan plan) {
        StringBuilder sb = new StringBuilder(1024);

        sb.append("    @Override public boolean equals(Object o) {\n");
        sb.append("        if (this == o) return true;\n");
        // Wildcards rather than the impl's own parameters: equals takes an
        // Object, so there is nothing to bind them to, and a raw type in an
        // instanceof pattern is rejected.
        sb.append("        if (!(o instanceof ").append(implName).append(wildcardArgs)
            .append(" other)) return false;\n");
        for (FieldSpec f : plan.compared()) {
            sb.append("        if (").append(notEqual(f)).append(") return false;\n");
        }
        sb.append("        return true;\n    }\n\n");

        sb.append("    @Override public int hashCode() {\n");
        sb.append("        final int PRIME = ").append(PRIME).append(";\n");
        sb.append("        int result = 1;\n");
        for (FieldSpec f : plan.compared()) {
            MemberShape shape = MemberShape.of(f.type);
            // The one row needing its value twice, and the one place a bit
            // pattern must not be recomputed: a double is folded from a local.
            if (shape == MemberShape.DOUBLE) {
                sb.append("        final long ").append(hashLocal(f)).append(" = ")
                    .append(DOUBLE_FQN).append(".doubleToLongBits(this.").append(f.name).append(");\n");
            }
            sb.append("        result = result * PRIME + ").append(hashTerm(f, shape)).append(";\n");
        }
        sb.append("        return result;\n    }\n\n");

        sb.append("    @Override public String toString() {\n");
        sb.append("        return \"").append(implName).append(plan.open()).append("\"\n");
        for (int i = 0; i < plan.printed().size(); i++) {
            ImplPlan.Printed printed = plan.printed().get(i);
            String prefix = (i == 0 ? "" : ", ")
                + (plan.includeFieldNames() ? printed.label() + "=" : "");
            sb.append("            + ");
            if (!prefix.isEmpty()) sb.append('"').append(prefix).append("\" + ");
            sb.append(print(printed.field())).append('\n');
        }
        sb.append("            + \"").append(plan.close()).append("\";\n    }\n\n");

        return sb.toString();
    }

    /**
     * The condition under which one member makes two instances unequal.
     *
     * <p>An array is read by content in both directions. Comparing one with
     * {@code Objects.equals} compares the two references, so two impls built
     * from identical builders come out unequal with nothing to say so.
     */
    private static String notEqual(FieldSpec f) {
        String mine = "this." + f.name;
        String theirs = "other." + f.name;
        switch (MemberShape.of(f.type)) {
            case BOOLEAN:
            case INTEGRAL:
            case LONG:
                return mine + " != " + theirs;
            // compare rather than !=, which is non-reflexive for NaN and
            // conflates the two zeroes - and induces the partition the
            // matching bits-based hash term does.
            case FLOAT:
                return FLOAT_FQN + ".compare(" + mine + ", " + theirs + ") != 0";
            case DOUBLE:
                return DOUBLE_FQN + ".compare(" + mine + ", " + theirs + ") != 0";
            case PRIMITIVE_ARRAY:
                return "!" + ARRAYS_FQN + ".equals(" + mine + ", " + theirs + ")";
            case DEEP_ARRAY:
                return "!" + ARRAYS_FQN + ".deepEquals(" + mine + ", " + theirs + ")";
            default:
                return "!" + OBJECTS_FQN + ".equals(" + mine + ", " + theirs + ")";
        }
    }

    /** The {@code int} one member contributes to the accumulator. */
    private static String hashTerm(FieldSpec f, MemberShape shape) {
        String read = "this." + f.name;
        switch (shape) {
            case BOOLEAN: return "(" + read + " ? 79 : 97)";
            case INTEGRAL: return read;
            case LONG: return "(int) (" + read + " ^ (" + read + " >>> 32))";
            case FLOAT: return FLOAT_FQN + ".floatToIntBits(" + read + ")";
            case DOUBLE: {
                String local = hashLocal(f);
                return "(int) (" + local + " ^ (" + local + " >>> 32))";
            }
            case PRIMITIVE_ARRAY:
                return ARRAYS_FQN + ".hashCode(" + read + ")";
            case DEEP_ARRAY:
                return ARRAYS_FQN + ".deepHashCode(" + read + ")";
            default:
                return "(" + read + " == null ? 43 : " + read + ".hashCode())";
        }
    }

    /** The printable form of one member - only an array needs anything. */
    private static String print(FieldSpec f) {
        String read = "this." + f.name;
        switch (MemberShape.of(f.type)) {
            case PRIMITIVE_ARRAY:
                return ARRAYS_FQN + ".toString(" + read + ")";
            case DEEP_ARRAY:
                return ARRAYS_FQN + ".deepToString(" + read + ")";
            default:
                return read;
        }
    }

    /**
     * The name of the local a {@code double} member's bit pattern is held in.
     * Prefixed out of the identifier space a field name can occupy, so it
     * cannot shadow the member it was derived from.
     */
    private static String hashLocal(FieldSpec f) {
        return "$hash$" + f.name;
    }

    /**
     * Renders {@code mirror} back to source as a trailing-space-terminated
     * annotation prefix, or {@code ""} when the accessor carried none.
     *
     * <p>Only the attributes the author actually wrote are emitted -
     * {@code getElementValues()} excludes defaulted ones - so the generated
     * field reads as the accessor did rather than spelling out all five.
     *
     * @param mirror the {@code @BuildFlag} mirror, or null
     * @param packageName the impl's package, for deciding whether to import
     * @param imports collector the annotation's own import is added to
     * @return the rendered prefix, empty when there is nothing to copy
     */
    private static String renderBuildFlag(AnnotationMirror mirror, String packageName, TreeSet<String> imports) {
        if (mirror == null) return "";
        StringBuilder sb = new StringBuilder(64);
        sb.append('@').append(considerImport(BUILD_FLAG_FQN, packageName, imports));
        Map<? extends ExecutableElement, ? extends AnnotationValue> written = mirror.getElementValues();
        if (!written.isEmpty()) {
            sb.append('(');
            boolean first = true;
            for (Map.Entry<? extends ExecutableElement, ? extends AnnotationValue> e : written.entrySet()) {
                if (!first) sb.append(", ");
                first = false;
                sb.append(e.getKey().getSimpleName()).append(" = ").append(renderValue(e.getValue().getValue()));
            }
            sb.append(')');
        }
        return sb.append(' ').toString();
    }

    /**
     * Renders an annotation attribute value as a Java source literal. Covers
     * the shapes {@code @BuildFlag} can carry - boolean, int, String, and
     * String array - with anything else falling through to its own
     * {@code toString}.
     *
     * @param value the unwrapped attribute value
     * @return the source literal
     */
    private static String renderValue(Object value) {
        if (value instanceof String s) return quote(s);
        if (value instanceof List<?> list) {
            StringBuilder sb = new StringBuilder("{");
            for (int i = 0; i < list.size(); i++) {
                if (i > 0) sb.append(", ");
                Object element = list.get(i);
                sb.append(renderValue(element instanceof AnnotationValue av ? av.getValue() : element));
            }
            return sb.append('}').toString();
        }
        return String.valueOf(value);
    }

    /**
     * Quotes a string as a Java literal, escaping everything outside printable
     * ASCII. A {@code pattern} regex routinely carries backslashes, so passing
     * the raw text through would produce source that fails to compile - or,
     * worse, compiles to a different regex.
     *
     * @param s the raw attribute value
     * @return the quoted literal
     */
    private static String quote(String s) {
        StringBuilder sb = new StringBuilder(s.length() + 2).append('"');
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\\') sb.append("\\\\");
            else if (c == '"') sb.append("\\\"");
            else if (c == '\n') sb.append("\\n");
            else if (c == '\r') sb.append("\\r");
            else if (c == '\t') sb.append("\\t");
            else if (c >= 0x20 && c < 0x7f) sb.append(c);
            else sb.append(String.format("\\u%04x", (int) c));
        }
        return sb.append('"').toString();
    }

    /**
     * The interface's type parameters in declaration form, bounds included -
     * {@code "<K, V extends Comparable<V>>"}. Empty when it is not generic.
     * {@code java.lang.Object} bounds are dropped, being what an unbounded
     * parameter means anyway.
     */
    private static String typeParamDecl(TypeElement target, String packageName, TreeSet<String> imports) {
        if (target.getTypeParameters().isEmpty()) return "";
        StringBuilder sb = new StringBuilder("<");
        boolean firstParam = true;
        for (TypeParameterElement tp : target.getTypeParameters()) {
            if (!firstParam) sb.append(", ");
            firstParam = false;
            sb.append(tp.getSimpleName());
            boolean firstBound = true;
            for (TypeMirror bound : tp.getBounds()) {
                if ("java.lang.Object".equals(bound.toString())) continue;
                sb.append(firstBound ? " extends " : " & ")
                    .append(simplifyType(bound.toString(), packageName, imports));
                firstBound = false;
            }
        }
        return sb.append('>').toString();
    }

    /** The interface's type parameters in reference form - {@code "<K, V>"}. */
    private static String typeArgs(TypeElement target) {
        if (target.getTypeParameters().isEmpty()) return "";
        StringBuilder sb = new StringBuilder("<");
        boolean first = true;
        for (TypeParameterElement tp : target.getTypeParameters()) {
            if (!first) sb.append(", ");
            first = false;
            sb.append(tp.getSimpleName());
        }
        return sb.append('>').toString();
    }

    /**
     * The impl's type parameters as wildcards - {@code "<?, ?>"} - which is what
     * the {@code instanceof} pattern in {@code equals} needs. One per parameter:
     * a single {@code <?>} for a two-parameter interface is a wrong-arity
     * reference, and the emitted file then fails to compile in a consumer's
     * build on a line they cannot edit.
     */
    private static String wildcardArgs(TypeElement target) {
        int count = target.getTypeParameters().size();
        return count == 0 ? "" : "<" + "?, ".repeat(count - 1) + "?>";
    }

    private static String simplifyType(String typeStr, String packageName, TreeSet<String> imports) {
        StringBuilder out = new StringBuilder(typeStr.length());
        int i = 0;
        int n = typeStr.length();
        while (i < n) {
            int tokenStart = i;
            while (i < n && (Character.isJavaIdentifierPart(typeStr.charAt(i)) || typeStr.charAt(i) == '.')) i++;
            String token = typeStr.substring(tokenStart, i);
            if (!token.isEmpty() && token.indexOf('.') >= 0 && Character.isJavaIdentifierStart(token.charAt(0))) {
                out.append(considerImport(token, packageName, imports));
            } else {
                out.append(token);
            }
            if (i < n) {
                out.append(typeStr.charAt(i));
                i++;
            }
        }
        return out.toString();
    }

    private static String considerImport(String fqn, String packageName, TreeSet<String> imports) {
        if (fqn.startsWith("java.lang.") && fqn.lastIndexOf('.') == "java.lang".length()) {
            return fqn.substring("java.lang.".length());
        }
        int lastDot = fqn.lastIndexOf('.');
        if (lastDot < 0) return fqn;
        String pkg = fqn.substring(0, lastDot);
        String simple = fqn.substring(lastDot + 1);
        if (pkg.equals(packageName)) return simple;
        imports.add(fqn);
        return simple;
    }

}
