    /**
     * The one input the two annotations differ on, and the difference is
     * visible in a single file: state left out of serialization is still state
     * a dump wants, and never part of the value.
     */
    public void testTransientStateIsPrintedAndNotCompared() {
        configure("app/Ping.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            import dev.simplified.annotations.ToString;
            @EqualsAndHashCode
            @ToString
            public class Ping {
                private String motd;
                private transient String cache;
            }
            """);
        assertTrue(sole(EQUALITY).contains("<br>Compares: motd"));
        assertFalse(sole(EQUALITY).contains("cache"));
        assertEquals("Generated by @ToString<br>Renders: Ping[motd=..., cache=...]",
            sole(TO_STRING));
    }

