    public void testMarkerDescribesAnAnnotatedClass() {
        configure("app/Token.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode
            public class Token {
                private String value;
                private long issued;
            }
            """);
        assertEquals("Generated by @EqualsAndHashCode"
                + "<br>Identity: this.getClass() == o.getClass()"
                + "<br>Compares: value, issued",
            sole(EQUALITY));
    }

    public void testIconResolvesToTheSharedResource() {
        configure("app/Token.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode
            public class Token { private String value; }
            """);
        assertSame("the gutter must reference " + ICON_PATH,
            IconLoader.getIcon(ICON_PATH, WholeObjectLineMarkerProvider.class),
            gutter(EQUALITY).getIcon());
    }

    /**
     * The wording a selection that reaches nothing produces, pinned because it
     * is also what a selection walk reading the wrong member list degrades to -
     * a description that is wrong and reads as deliberate.
     */
    public void testAnEmptySelectionSaysSoInFull() {
        configure("app/Marker.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode
            public class Marker {
                private static final String TAG = "marker";
            }
            """);
        assertEquals("Generated by @EqualsAndHashCode"
                + "<br>Identity: this.getClass() == o.getClass()"
                + "<br>Compares no members - every instance compares equal to every other",
            sole(EQUALITY));
    }

    public void testInstanceOfIsSpelledAsATypeTest() {
        configure("app/Token.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode(identity = EqualsAndHashCode.Identity.INSTANCE_OF)
            public class Token { private String value; }
            """);
        assertTrue(sole(EQUALITY).contains("<br>Identity: o instanceof Token<br>"));
    }

    public void testTheCooperatingRelationNamesTheHook() {
        configure("app/Token.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode(identity = EqualsAndHashCode.Identity.INSTANCE_OF_CANEQUAL)
            public class Token { private String value; }
            """);
        assertTrue(sole(EQUALITY).contains(
            "o instanceof Token, asked back through a protected canEqual hook"));
    }

    /** The gutter has to say the hook degraded away, since nothing else does. */
    public void testTheCooperatingRelationOnAFinalRootTypeSaysTheHookIsGone() {
        configure("app/Token.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode(identity = EqualsAndHashCode.Identity.INSTANCE_OF_CANEQUAL)
            public final class Token { private String value; }
            """);
        assertTrue(sole(EQUALITY).contains("no canEqual hook, since no subclass of a final root "
            + "type can override it"));
    }

    public void testTheMarkerFollowsTheNarrowingAttributes() {
        configure("app/Token.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            import dev.simplified.annotations.EqualsExclude;
            @EqualsAndHashCode(exclude = "issued")
            public class Token {
                private String value;
                private long issued;
                @EqualsExclude private long checksum;
            }
            """);
        assertTrue(sole(EQUALITY).contains("<br>Compares: value"));
        assertFalse("the attribute takes it out", sole(EQUALITY).contains("issued"));
        assertFalse("and so does the marker", sole(EQUALITY).contains("checksum"));
    }

    public void testTheSuperCallIsShownWhenTheSuperclassSuppliesThePair() {
        myFixture.addFileToProject("app/Base.java",
            """
            package app;
            public class Base {
                @Override
                public boolean equals(Object o) { return this == o; }
                @Override
                public int hashCode() { return 0; }
            }
            """);
        configure("app/Child.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode
            public class Child extends Base { private String label; }
            """);
        assertTrue(sole(EQUALITY).contains("<br>Calls super.equals and super.hashCode"));
    }

    public void testNoSuperCallIsShownWhenTheSuperclassSuppliesNeither() {
        myFixture.addFileToProject("app/Base.java",
            """
            package app;
            public class Base { protected int tag; }
            """);
        configure("app/Child.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode
            public class Child extends Base { private String label; }
            """);
        assertFalse(sole(EQUALITY).contains("Calls super"));
    }

    public void testTheMemoAndTheAccessorReadsAreAnnounced() {
        configure("app/Token.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode(cacheHashCode = true, useAccessors = true)
            public final class Token {
                private final String value = "";
                public String value() { return this.value; }
            }
            """);
        String tooltip = sole(EQUALITY);
        assertTrue(tooltip.contains("<br>Memoizes the hash in a transient $hashCode field"));
        assertTrue(tooltip.contains("<br>Reads each member through its declared accessor"));
    }

