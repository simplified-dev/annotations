    // ------------------------------------------------------------------
    // A hierarchy that does not terminate
    // ------------------------------------------------------------------

    /**
     * A cyclic {@code extends} is the ordinary state of a file mid-rename, and
     * the platform resolves one without complaint. The tooltip's superclass
     * walk runs on the daemon thread, so an unguarded loop there is a frozen
     * IDE rather than a wrong answer - a marker that is produced at all is the
     * assertion.
     */
    public void testASelfExtendingTargetStillProducesAMarker() {
        configure("app/Loop.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            @EqualsAndHashCode
            public class Loop extends Loop { private String value; }
            """);
        assertTrue(marked(EQUALITY));
    }

    public void testMutuallyExtendingTargetsStillProduceAMarker() {
        myFixture.addFileToProject("app/Down.java",
            """
            package app;
            public class Down extends Up { }
            """);
        configure("app/Up.java",
            """
            package app;
            import dev.simplified.annotations.ToString;
            @ToString
            public class Up extends Down { private String value; }
            """);
        assertTrue(marked(TO_STRING));
    }

