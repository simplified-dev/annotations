    /**
     * A record's component-backed fields never appear among the fields the
     * class itself declares, so a member walk that reads only those answers
     * with nothing at all - and the tooltip then states the opposite of what is
     * generated, on the one target kind the annotation exists for.
     */
    public void testARecordIsDescribedThroughItsComponents() {
        configure("app/Pixels.java",
            """
            package app;
            import dev.simplified.annotations.EqualsAndHashCode;
            import dev.simplified.annotations.EqualsExclude;
            @EqualsAndHashCode
            public record Pixels(int width, @EqualsExclude int height) { }
            """);
        assertEquals("Generated by @EqualsAndHashCode"
                + "<br>Identity: this.getClass() == o.getClass()"
                + "<br>Compares: width",
            sole(EQUALITY));
    }

